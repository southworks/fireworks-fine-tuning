#!/usr/bin/env python3
"""Build Markdown result tables for the Amazon purchase-decision benchmark.

Offline and deterministic: reads the frozen files in an evaluation folder and
writes RESULTS.md. Inputs (relative to --dir):
  decision_metrics_all_models.json   label metrics (scripts/decision_metrics.py)
  metrics_all_models.json            reference-overlap metrics (scripts/benchmark.py summarize)
  judge_summary*.json                one table per judge session
  predictions_*.jsonl                tokens and latency
"""

from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

LABELS = ("BUY", "CONDITIONAL_BUY", "DO_NOT_BUY", "INSUFFICIENT_EVIDENCE")
ORDER = ["Qwen3-4B FT v2", "Qwen3-4B fine-tuned", "GPT-4.1 mini", "GPT-5", "Qwen3-4B base"]


def display_name(model: str) -> str:
    if "amazon-v2" in model:
        return "Qwen3-4B FT v2"
    if "#" in model or "/models/ft-" in model:
        return "Qwen3-4B fine-tuned"
    if "deployments/" in model or "qwen3-4b" in model:
        return "Qwen3-4B base"
    return {"gpt-5": "GPT-5", "gpt-4.1-mini": "GPT-4.1 mini"}.get(model, model)


def rank(name: str) -> int:
    return ORDER.index(name) if name in ORDER else len(ORDER)


def read_jsonl(path: Path):
    with path.open(encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def usage_stats(path: Path) -> tuple[str, dict]:
    rows = read_jsonl(path)
    inp = [r["usage"].get("prompt_tokens", r["usage"].get("input_tokens", 0)) for r in rows]
    out = [r["usage"].get("completion_tokens", r["usage"].get("output_tokens", 0)) for r in rows]
    reasoning = [((r["usage"].get("output_tokens_details") or {}).get("reasoning_tokens") or 0) for r in rows]
    lat = sorted(r["latency_seconds"] for r in rows)
    return display_name(rows[0]["model"]), {
        "n": len(rows),
        "errors": sum(1 for r in rows if r.get("error")),
        "input_tokens": sum(inp),
        "output_tokens": sum(out),
        "reasoning_tokens": sum(reasoning),
        "total_tokens": sum(inp) + sum(out),
        "latency_mean": statistics.mean(lat),
        "latency_p50": statistics.median(lat),
        "latency_p95": lat[min(len(lat) - 1, int(round(0.95 * (len(lat) - 1))))],
    }


def pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.2f}%"


def build(folder: Path) -> str:
    decisions = json.loads((folder / "decision_metrics_all_models.json").read_text())
    overlap = json.loads((folder / "metrics_all_models.json").read_text())
    models = sorted(decisions["models"].items(), key=lambda kv: rank(display_name(kv[0])))
    ref = decisions["reference_distribution"]

    lines = ["# Amazon v2 benchmark results", "",
             "Generated by `scripts/build_report.py` from the frozen files in this folder. Do not edit by hand.", "",
             f"Cases: {sum(ref.values())}. Reference distribution: "
             + ", ".join(f"{ref.get(l, 0)} `{l}`" for l in LABELS) + ".", "",
             "## 1. Purchase decision against the reference label", "",
             "| Model | Accuracy | Macro-F1 | Weighted-F1 | Token-F1 | ROUGE-L F1 | " + " | ".join(f"`{l}` predicted" for l in LABELS) + " |",
             "|---|---:|---:|---:|---:|---:|" + "---:|" * len(LABELS)]
    for model, m in models:
        o = overlap["models"].get(model, {}).get("overall", {})
        dist = m["prediction_distribution"]
        lines.append(f"| {display_name(model)} | {pct(m['accuracy'])} | {m['macro_f1']:.4f} | {m['weighted_f1']:.4f} | "
                     f"{o.get('token_f1', 0):.4f} | {o.get('rouge_l_f1', 0):.4f} | " + " | ".join(str(dist.get(l, 0)) for l in LABELS) + " |")
    lines.append("| Reference | | | | | | " + " | ".join(str(ref.get(l, 0)) for l in LABELS) + " |")

    lines += ["", "## 2. Per-class F1", "", "| Model | " + " | ".join(f"`{l}`" for l in LABELS) + " |", "|---|" + "---:|" * len(LABELS)]
    for model, m in models:
        lines.append(f"| {display_name(model)} | " + " | ".join(f"{m['per_class'][l]['f1']:.4f}" for l in LABELS) + " |")

    lines += ["", "## 3. Blind LLM judge (GPT-6 Sol)", "",
              "The judge sees three anonymized, shuffled answers per case. Each session is a separate run with a different "
              "candidate set, so scores are comparable **within** a session, not across sessions.", ""]
    for index, path in enumerate(sorted(folder.glob("judge_summary*.json"))):
        judge = json.loads(path.read_text())
        order = ["Qwen3-4B base", "Qwen3-4B FT v2", "Qwen3-4B fine-tuned", "GPT-4.1 mini", "GPT-5"]
        names = sorted((display_name(m) for m in judge["models"]), key=lambda n: order.index(n) if n in order else 99)
        title = f"Session {chr(65 + index)}: " + " vs ".join(names)
        lines += [f"### {title} ({judge['successful_judgments']}/{judge['cases']} valid judgments)", "",
                  "| Model | Score /100 | Grounding | Coverage | Rules | Calibration | Catalog/user separation | Actionability | Pass rate | Critical errors | Unsupported claim | Preferred |",
                  "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for model, s in sorted(judge["models"].items(), key=lambda kv: -kv[1]["overall"]["overall_score"]):
            o = s["overall"]
            lines.append(f"| {display_name(model)} | {o['overall_score']:.2f} | {o['groundedness']:.2f} | {o['evidence_coverage']:.2f} | {o['rule_compliance']:.2f} | "
                         f"{o['severity_calibration']:.2f} | {o['catalog_user_separation']:.2f} | {o['actionability']:.2f} | {pct(o['pass_rate'])} | "
                         f"{pct(o['critical_error_rate'])} | {pct(o['unsupported_claim_rate'])} | {s['wins']}/{o['n']} ({pct(s['win_rate'])}) |")
        lines.append("")

    usage = dict(usage_stats(p) for p in sorted(folder.glob("predictions_*.jsonl")))
    lines += ["## 4. Tokens and latency (103 requests)", "",
              "| Model | Errors | Input tokens | Output tokens | of which reasoning | Total tokens | Mean latency | p50 | p95 |",
              "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for name, u in sorted(usage.items(), key=lambda kv: rank(kv[0])):
        lines.append(f"| {name} | {u['errors']} | {u['input_tokens']:,} | {u['output_tokens']:,} | {u['reasoning_tokens']:,} | {u['total_tokens']:,} | "
                     f"{u['latency_mean']:.2f} s | {u['latency_p50']:.2f} s | {u['latency_p95']:.2f} s |")
    lines += ["", "Qwen models ran on Fireworks dedicated deployments; GPT models ran on Microsoft Foundry. Latencies are observed "
              "end-to-end values from different providers, not architecture comparisons.", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dir", type=Path, default=Path(__file__).resolve().parents[1] / "evaluation" / "qwen3-4b-amazon-v2")
    parser.add_argument("--output", default="RESULTS.md")
    parser.add_argument("--check", action="store_true", help="fail if the existing file differs from a fresh build")
    args = parser.parse_args()
    text = build(args.dir)
    target = args.dir / args.output
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{target} is stale; run without --check to regenerate")
        print(f"{target} is up to date")
        return
    target.write_text(text, encoding="utf-8")
    print(target)


if __name__ == "__main__":
    main()
